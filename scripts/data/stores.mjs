/** Retail price rounding: keep charm pricing and honour the 72% margin floor. */
export function pricePoint(raw, marginFloor = 0.72) {
  const min = Math.ceil(raw / (1 - marginFloor));
  // round up to the next "charm" price: 9 / 19 / 29 / 34 / 39 / 44 / 49 / 54 / 59 / 64 ...
  const steps = [9, 14, 19, 24, 29, 34, 39, 44, 49, 54, 59, 64, 69, 74, 79, 84, 89, 94, 99, 109, 119, 129, 139, 149, 169, 189, 209, 229, 249, 299];
  for (const s of steps) if (s >= min) return s;
  return Math.ceil(min / 10) * 10 - 1;
}

export function buildCatalog(store) {
  const rows = [];
  const h = store.hero;
  const heroPrice = pricePoint(h.cost);
  rows.push({
    skuIndex: 1,
    sku: `${store.skuPrefix}001`,
    title: h.title,
    handle: slug(h.title),
    category: h.category,
    price: heroPrice,
    cost: round2(h.cost),
    compareAt: pricePoint(h.cost * 1.45),
    summary: h.summary,
    features: h.features,
    isHero: true,
  });
  store.catalog.forEach((row, i) => {
    const [title, , cost, category, summary] = row;
    rows.push({
      skuIndex: i + 2,
      sku: `${store.skuPrefix}${String(i + 2).padStart(3, "0")}`,
      title,
      handle: slug(title),
      category,
      price: pricePoint(cost),
      cost: round2(cost),
      compareAt: pricePoint(cost * 1.45),
      summary,
      features: [summary],
      isHero: false,
    });
  });
  return rows.map((r) => {
    const gross = r.price - r.cost;
    const margin = gross / r.price;
    const tier2 = round2(r.price * 2 * 0.85);
    const tier3 = round2(r.price * 3 * 0.75);
    return {
      ...r,
      marginPercent: Math.round(margin * 1000) / 10,
      marginUSD: round2(gross),
      bundle: {
        tier1: { qty: 1, label: "Starter", price: r.price, savings: 0 },
        tier2: { qty: 2, label: "Duo Bundle", price: tier2, savings: round2(r.price * 2 - tier2), save: "15%", shipping: "Free Shipping" },
        tier3: { qty: 3, label: "Collector Vault", price: tier3, savings: round2(r.price * 3 - tier3), save: "25%", shipping: "Free Shipping", bonus: "Free Companion Gift" },
      },
    };
  });
}

export function round2(n) {
  return Math.round(n * 100) / 100;
}

export function slug(s) {
  return String(s)
    .toLowerCase()
    .replace(/™|®/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}
